"""Leaderboard of every run in outputs/runs -> outputs/report.{md,json}."""

from __future__ import annotations

import json

from . import OUTPUT_DIR, RUNS_DIR

COLS = [
    ("run", lambda s: f"`{s['run_id']}`"),
    ("mode", lambda s: s["mode"]),
    ("type", lambda s: s["params"].get("search_type", "-")),
    ("n", lambda s: s["n_requests"]),
    ("p50 ms", lambda s: s["latency_ms"]["p50"]),
    ("p95 ms", lambda s: s["latency_ms"]["p95"]),
    ("err", lambda s: f"{s['error_rate']:.0%}"),
    ("zero", lambda s: f"{s['zero_result_rate']:.0%}"),
    ("hit@1", lambda s: f"{s['anchor']['hit_at_1']:.0%}"),
    ("hit@k", lambda s: f"{s['anchor']['hit_at_k']:.0%}"),
    ("obj cov", lambda s: f"{s['objective_coverage']:.0%}"),
    ("registry", lambda s: f"{s['source_mix'].get('registry', 0):.0%}"),
    ("lit", lambda s: f"{s['source_mix'].get('literature', 0):.0%}"),
    ("cost $", lambda s: s["cost_usd"]),
    ("review prec", lambda s: f"{s['review']['precision']:.0%}" if s.get("review") else "-"),
]


def build_report() -> tuple[str, list[dict]]:
    summaries = []
    for path in sorted(RUNS_DIR.glob("*/summary.json")):
        summaries.append(json.loads(path.read_text(encoding="utf-8")))
    lines = ["# Run leaderboard", "",
             "Auto-generated by `wsx report`. Metric definitions: docs/METHODOLOGY.md.", "",
             "| " + " | ".join(c for c, _ in COLS) + " |", "|" + "---|" * len(COLS)]
    for s in summaries:
        lines.append("| " + " | ".join(str(fn(s)) for _, fn in COLS) + " |")
    md = "\n".join(lines) + "\n"
    OUTPUT_DIR.mkdir(exist_ok=True)
    (OUTPUT_DIR / "report.md").write_text(md, encoding="utf-8")
    compact = [{"run_id": s["run_id"], **{c: fn(s) for c, fn in COLS[1:]}} for s in summaries]
    (OUTPUT_DIR / "report.json").write_text(json.dumps(compact, indent=2), encoding="utf-8")
    return md, summaries
