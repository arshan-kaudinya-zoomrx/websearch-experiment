"""Leaderboard of every run in outputs/runs -> outputs/report.{md,json}."""

from __future__ import annotations

import json

from . import FILTERS_DIR, JUDGE_DIR, OUTPUT_DIR, RUNS_DIR, SYNTH_DIR

COLS = [
    ("run", lambda s: f"`{s['run_id']}`"),
    ("mode", lambda s: s["mode"]),
    ("provider", lambda s: s.get("provider", "-")),
    ("type", lambda s: s["params"].get("search_type") or s["params"].get("mode") or "-"),
    ("n", lambda s: s["n_requests"]),
    ("p50 ms", lambda s: s["latency_ms"]["p50"]),
    ("p95 ms", lambda s: s["latency_ms"]["p95"]),
    ("err", lambda s: f"{s['error_rate']:.0%}"),
    ("zero", lambda s: f"{s['zero_result_rate']:.0%}"),
    ("hit@1", lambda s: f"{s['anchor']['hit_at_1']:.0%}"),
    ("hit@k", lambda s: f"{s['anchor']['hit_at_k']:.0%}"),
    ("obj cov", lambda s: f"{s['objective_coverage']:.0%}"),
    ("registry", lambda s: f"{s['source_mix'].get('registry', 0):.0%}"),
    ("lit", lambda s: f"{s['source_mix'].get('literature', 0):.0%}"),
    ("cost $", lambda s: s["cost_usd"]),
    ("review prec", lambda s: f"{s['review']['precision']:.0%}" if s.get("review") else "-"),
]


def _ba(d: dict) -> str:
    return f"{d['without_jev']:.0%}→{d['with_jev']:.0%}"


FILTER_COLS = [
    ("filter", lambda s: f"`{s['filter_id']}`"),
    ("source", lambda s: f"{s.get('source_mode')}/{(s.get('source_params') or {}).get('search_type', '-')}"),
    ("gran", lambda s: s["granularity"]),
    ("select", lambda s: (" ".join(f"{g}≥{v}" for g, v in s["select"]["gates"].items())
                          if s["select"].get("gates") else f"≥{s['select']['keep_threshold']}")
                         + f" max {s['select']['max_keep']}"),
    ("n", lambda s: s["n_scored"]),
    ("err", lambda s: f"{s['error_rate']:.0%}"),
    ("search p50", lambda s: s["timing_ms"]["search"]["p50"]),
    ("jev p50", lambda s: s["timing_ms"]["jev"]["p50"]),
    ("jev p95", lambda s: s["timing_ms"]["jev"]["p95"]),
    ("total p50", lambda s: s["timing_ms"]["total"]["p50"]),
    ("kept/list", lambda s: f"{s['selection']['kept_mean']}/{s['selection']['candidates_mean']}"),
    ("abstain", lambda s: f"{s['selection']['abstain_rate']:.0%}"),
    ("anchor prec", lambda s: _ba(s["quality"]["anchor_precision"])),
    ("hit@1", lambda s: _ba(s["quality"]["hit_at_1"])),
    ("obj cov", lambda s: _ba(s["quality"]["objective_coverage"])),
    ("recall kept", lambda s: f"{s['quality']['anchor_recall_retained']:.0%}"),
    ("cost $", lambda s: s["cost_usd"]),
]

SYNTH_COLS = [
    ("synth", lambda s: f"`{s['synth_id']}`"),
    ("arm", lambda s: s["arm"]),
    ("model", lambda s: s["model"]),
    ("n", lambda s: s["n_rows"]),
    ("answered", lambda s: f"{s['answering']['answer_rate']:.0%}"),
    ("jev abstain", lambda s: f"{s['answering']['jev_abstain_rate']:.0%}"),
    ("complete", lambda s: f"{s['answering']['complete_rate']:.0%}"),
    ("ungrounded tok", lambda s: f"{s['grounding']['ungrounded_token_rate']:.1%}"),
    ("search-talk", lambda s: f"{s['contract']['search_talk_rows']:.0%}"),
    ("items", lambda s: s["evidence_use"]["items_given_mean"]),
    ("cited", lambda s: s["evidence_use"]["items_cited_mean"]),
    ("luna p50", lambda s: s["luna_timing_ms_called"]["p50"]),
    ("total p50", lambda s: s["timing_ms"]["total"]["p50"]),
    ("total p95", lambda s: s["timing_ms"]["total"]["p95"]),
    ("$ / answer", lambda s: s["cost_usd"]["per_answer"]),
]


def build_report() -> tuple[str, list[dict]]:
    summaries = []
    for path in sorted(RUNS_DIR.glob("*/summary.json")):
        summaries.append(json.loads(path.read_text(encoding="utf-8")))
    lines = ["# Run leaderboard", "",
             "Auto-generated by `wsx report`. Metric definitions: docs/METHODOLOGY.md.", "",
             "| " + " | ".join(c for c, _ in COLS) + " |", "|" + "---|" * len(COLS)]
    for s in summaries:
        lines.append("| " + " | ".join(str(fn(s)) for _, fn in COLS) + " |")
    filters = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(FILTERS_DIR.glob("*/summary.json"))]
    if filters:
        lines += ["", "## Jev filters", "",
                  "Without→with Jev. Timing: search replayed from the source run + measured Jev time.", "",
                  "| " + " | ".join(c for c, _ in FILTER_COLS) + " |", "|" + "---|" * len(FILTER_COLS)]
        for s in filters:
            lines.append("| " + " | ".join(str(fn(s)) for _, fn in FILTER_COLS) + " |")
    synths = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(SYNTH_DIR.glob("*/summary.json"))]
    if synths:
        lines += ["", "## Luna answers", "",
                  "Code-only answer metrics per arm (docs/METHODOLOGY.md, \"Luna answers\"). Judge results: "
                  "outputs/judge/*/compare.md.", "",
                  "| " + " | ".join(c for c, _ in SYNTH_COLS) + " |", "|" + "---|" * len(SYNTH_COLS)]
        for s in synths:
            lines.append("| " + " | ".join(str(fn(s)) for _, fn in SYNTH_COLS) + " |")
    judges = sorted(JUDGE_DIR.glob("*/compare.md"))
    if judges:
        lines += ["", "## Judge comparisons", ""] + [f"- `{p.parent.name}`: {p.relative_to(OUTPUT_DIR).as_posix()}"
                                                    for p in judges]
    md = "\n".join(lines) + "\n"
    OUTPUT_DIR.mkdir(exist_ok=True)
    (OUTPUT_DIR / "report.md").write_text(md, encoding="utf-8")
    compact = {
        "runs": [{"run_id": s["run_id"], **{c: fn(s) for c, fn in COLS[1:]}} for s in summaries],
        "filters": [{"filter_id": s["filter_id"], **{c: fn(s) for c, fn in FILTER_COLS[1:]}} for s in filters],
        "synth": [{"synth_id": s["synth_id"], **{c: fn(s) for c, fn in SYNTH_COLS[1:]}} for s in synths],
    }
    (OUTPUT_DIR / "report.json").write_text(json.dumps(compact, indent=2, ensure_ascii=False), encoding="utf-8")
    return md, summaries
